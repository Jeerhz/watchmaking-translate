// Regenerate lib/results.ts from the retrieval benchmark (`uv run trad-gmt retrieval-eval`).
import { readFileSync, writeFileSync } from "node:fs";

const data = JSON.parse(readFileSync(new URL("../../data/eval/retrieval.json", import.meta.url), "utf-8"));
const out = `// Generated by scripts/results.mjs from data/eval/retrieval.json — do not edit by hand.

export type Metric = "tgt_uni" | "tgt_bi" | "src_bi" | "terms" | "exact";

export interface RetrievalReport {
  pool: string;
  memory_size: number;
  queries: number;
  k: number;
  model: string;
  results: ({ method: string } & Record<Metric, number>)[];
}

export const RETRIEVAL: RetrievalReport[] = ${JSON.stringify(data, null, 2)};
`;
writeFileSync(new URL("../lib/results.ts", import.meta.url), out);
console.log(`${data.length} reports → lib/results.ts`);
